export function makeT(lang) {
  const dict = TEXT[lang] || TEXT.id;
  return (key, vars) => {
    let s = dict[key] ?? TEXT.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}

const DB_CODES = ['FULL', 'CLOSED', 'DUPLICATE', 'NO_ACCESS', 'NAME_REQUIRED', 'KECAMATAN_REQUIRED', 'KECAMATAN_INVALID', 'NOT_FOUND'];

// Turns a database error into a screen message.
export function dbMessage(t, error) {
  const msg = String((error && error.message) || '');
  const code = DB_CODES.find((c) => msg.includes(c));
  return t(code ? `err.${code}` : 'err.generic');
}

// Turns a server endpoint error code into a screen message.
export function apiMessage(t, code) {
  const key = `api.${code}`;
  const s = t(key);
  return s === key ? t('api.generic') : s;
}

export function fmtTime(ts, lang) {
  if (!ts) return '';
  const d = new Date(ts);
  const loc = lang === 'en' ? 'en-GB' : 'id-ID';
  const time = d.toLocaleTimeString(loc, { hour: '2-digit', minute: '2-digit' });
  if (d.toDateString() === new Date().toDateString()) return time;
  return `${d.toLocaleDateString(loc, { day: 'numeric', month: 'short' })} ${time}`;
}
